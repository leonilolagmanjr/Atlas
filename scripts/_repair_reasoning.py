"""One-shot diagnose-and-repair for reasoning behavior tests (run from root).

Writes scripts/_repair_report.txt with exact code regions, applies the guarded
router fix (explicit_web_request signal), then re-runs the behavior tests and
the full suite, appending results to the report.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

REPORT = ROOT / "scripts" / "_repair_report.txt"
OUT: list[str] = []


def note(line: str = "") -> None:
    OUT.append(line)


def dump_region(path: str, pattern: str, label: str, before: int = 2, after: int = 30) -> None:
    lines = (ROOT / path).read_text(encoding="utf-8").splitlines()
    shown = set()
    for i, line in enumerate(lines):
        if re.search(pattern, line) and i not in shown:
            lo, hi = max(0, i - before), min(len(lines), i + after)
            note(f"--- {label} ({path} lines {lo + 1}-{hi}) ---")
            for j in range(lo, hi):
                note(f"{j + 1}: {lines[j]}")
                shown.add(j)
            note("")


def main() -> int:
    note("REPAIR REPORT - generated by scripts/_repair_reasoning.py")

    # 1. Ground-truth dumps -------------------------------------------------
    dump_region("reasoning/reasoning_engine.py", r"def handle_request", "engine.handle_request", 0, 75)
    dump_region("reasoning/reasoning_engine.py", r"def _gather", "engine._gather*", 0, 45)
    dump_region("reasoning/reasoning_engine.py", r"retrieved_chunks|retrieve\(", "engine.retrieve-usage", 6, 8)
    dump_region("reasoning/reasoning_engine.py", r"delegate|_pipeline|requires_action|request_type", "engine.delegation", 4, 10)
    dump_region("reasoning/query_router.py", r"explicit_web_request|time_sensitive", "router.signals", 8, 8)
    dump_region("reasoning/query_router.py", r"_TIME_SENSITIVE_TERMS|_MEMORY_TERMS", "router.term-tuples", 0, 10)
    dump_region("brain.py", r"retrieve|_knowledge|knowledge_search", "brain.retrieve-wiring", 6, 20)
    note("=== FULL test file: tests/test_reasoning_behavior.py ===")
    note((ROOT / "tests" / "test_reasoning_behavior.py").read_text(encoding="utf-8"))

    probe = ROOT / "scripts" / "_probe_api.py"
    if probe.exists():
        probe.unlink()
        note("cleanup: removed scripts/_probe_api.py")

    # 2. Guarded router fix ---------------------------------------------------
    qpath = ROOT / "reasoning" / "query_router.py"
    qsrc = qpath.read_text(encoding="utf-8")
    if "_WEB_REQUEST_TERMS" not in qsrc:
        terms = (
            "#: Explicit requests to use the internet as the information source.\n"
            "_WEB_REQUEST_TERMS: tuple[str, ...] = (\n"
            '    "search the web", "search the internet", "web search", "internet search",\n'
            '    "search online", "look online", "look it up online", "browse the web",\n'
            '    "go online", "google it", "use the internet", "use the web",\n'
            '    "on the internet", "on the web",\n'
            ")\n\n"
        )
        m = re.search(r"^_(?:TIME_SENSITIVE_TERMS|MEMORY_TERMS):", qsrc, re.M)
        if m:
            qsrc = qsrc[: m.start()] + terms + qsrc[m.start():]
            note("router: inserted _WEB_REQUEST_TERMS tuple")
        else:
            note("router: no anchor found for terms tuple (see dump)")
    m = re.search(r"explicit_web_request\s*=\s*([^,\n]+),", qsrc)
    if m:
        window = qsrc[max(0, m.start() - 4000): m.end() + 4000]
        if "lowered" in window:
            qsrc = (
                qsrc[: m.start()]
                + "explicit_web_request=_matches_terms(lowered, _WEB_REQUEST_TERMS),"
                + qsrc[m.end():]
            )
            note("router: explicit_web_request now derived from _WEB_REQUEST_TERMS")
        else:
            note("router: assignment left untouched; 'lowered' not in scope (see dump)")
    else:
        note("router: no explicit_web_request assignment matched (see dump)")
    qpath.write_text(qsrc, encoding="utf-8")

    # 3. Test runs -------------------------------------------------------------
    def run_pytest(args: list[str]) -> str:
        proc = subprocess.run(
            [sys.executable, "-m", "pytest", *args],
            cwd=ROOT, capture_output=True, text=True,
            encoding="utf-8", errors="replace", timeout=900,
        )
        return (proc.stdout or "") + (proc.stderr or "")

    note("=== behavior tests (one-line failures) ===")
    out = run_pytest(["tests/test_reasoning_behavior.py", "-q", "--tb=line", "-p", "no:cacheprovider"])
    note("\n".join(out.splitlines()[-20:]))
    print("\n".join(out.splitlines()[-12:]))
    note("=== full suite ===")
    out = run_pytest(["tests/", "-q", "-p", "no:cacheprovider", "--ignore=tests/test_api.py"])
    note("\n".join(out.splitlines()[-12:]))

    REPORT.write_text("\n".join(OUT), encoding="utf-8")
    print(f"report written: {REPORT} ({len(OUT)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
